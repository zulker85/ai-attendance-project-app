create table if not exists public.students (
    student_id bigint generated by default as identity primary key,
    name text not null,
    face_embedding double precision[],
    voice_embedding double precision[],
    face_consent_at timestamptz,
    voice_consent_at timestamptz
);

alter table public.students
    add column if not exists face_consent_at timestamptz,
    add column if not exists voice_consent_at timestamptz;

alter table public.students enable row level security;
grant select, insert, update on public.students to service_role;
grant usage, select on sequence public.students_student_id_seq to service_role;

notify pgrst, 'reload schema';
