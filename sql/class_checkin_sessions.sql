create table if not exists public.class_sessions (
    session_id bigint generated by default as identity primary key,
    subject_id bigint not null references public.subjects(subject_id) on delete cascade,
    teacher_id bigint not null references public.teachers(teacher_id) on delete cascade,
    access_code text not null unique check (access_code ~ '^[0-9]{8}$'),
    started_at timestamptz not null default now(),
    expires_at timestamptz not null,
    closed_at timestamptz,
    check (expires_at > started_at)
);

create index if not exists class_sessions_by_teacher
    on public.class_sessions (teacher_id, started_at desc);

alter table public.students
    add column if not exists face_consent_at timestamptz,
    add column if not exists voice_consent_at timestamptz;

alter table public.attendance_logs
    add column if not exists class_session_id bigint
    references public.class_sessions(session_id) on delete set null;

create index if not exists attendance_logs_by_class_session
    on public.attendance_logs (class_session_id)
    where class_session_id is not null;

create unique index if not exists one_attendance_record_per_student_session
    on public.attendance_logs (class_session_id, student_id)
    where class_session_id is not null;

create table if not exists public.class_checkins (
    checkin_id bigint generated by default as identity primary key,
    session_id bigint not null references public.class_sessions(session_id) on delete cascade,
    student_id bigint not null references public.students(student_id) on delete cascade,
    submitted_at timestamptz not null default now(),
    verification_method text not null check (verification_method in ('face', 'voice')),
    verification_score double precision not null,
    latitude double precision check (latitude between -90 and 90),
    longitude double precision check (longitude between -180 and 180),
    location_accuracy_m double precision check (
        location_accuracy_m is null
        or (location_accuracy_m >= 0
            and location_accuracy_m < 'Infinity'::double precision)
    ),
    risk_flags text[] not null default '{}',
    status text not null check (status in ('pending', 'approved', 'rejected')),
    reviewed_at timestamptz,
    reviewed_by bigint references public.teachers(teacher_id) on delete set null,
    unique (session_id, student_id),
    check ((latitude is null) = (longitude is null))
);

create index if not exists class_checkins_pending_by_session
    on public.class_checkins (session_id, submitted_at desc)
    where status = 'pending';

alter table public.class_sessions enable row level security;
alter table public.class_checkins enable row level security;
grant select, insert, update on public.class_sessions to service_role;
grant select, insert, update on public.class_checkins to service_role;
grant usage, select on sequence public.class_sessions_session_id_seq to service_role;
grant usage, select on sequence public.class_checkins_checkin_id_seq to service_role;

create or replace function public.open_class_session(
    p_subject_id bigint,
    p_teacher_id bigint,
    p_access_code text,
    p_duration_minutes integer
)
returns setof public.class_sessions
language plpgsql
security invoker
set search_path = ''
as $$
declare
    v_session public.class_sessions%rowtype;
    v_previous public.class_sessions%rowtype;
begin
    if p_duration_minutes < 1 or p_duration_minutes > 60
       or p_access_code !~ '^[0-9]{8}$' then
        raise exception 'Invalid check-in code or duration.';
    end if;

    perform 1
    from public.subjects
    where subject_id = p_subject_id
      and teacher_id = p_teacher_id
    for update;

    if not found then
        raise exception 'This subject does not belong to the signed-in teacher.';
    end if;

    for v_previous in
        select *
        from public.class_sessions
        where subject_id = p_subject_id
          and closed_at is null
        for update
    loop
        update public.class_sessions
        set closed_at = now()
        where session_id = v_previous.session_id;

        insert into public.attendance_logs (
            student_id, subject_id, timestamp, is_present, class_session_id
        )
        select enrollment.student_id,
               v_previous.subject_id,
               now(),
               false,
               v_previous.session_id
        from public.subject_students as enrollment
        where enrollment.subject_id = v_previous.subject_id
          and not exists (
              select 1
              from public.class_checkins as checkin
              where checkin.session_id = v_previous.session_id
                and checkin.student_id = enrollment.student_id
          )
        on conflict (class_session_id, student_id)
            where class_session_id is not null
            do nothing;
    end loop;

    insert into public.class_sessions (
        subject_id, teacher_id, access_code, expires_at
    )
    values (
        p_subject_id,
        p_teacher_id,
        p_access_code,
        now() + make_interval(mins => p_duration_minutes)
    )
    returning * into v_session;

    return next v_session;
end;
$$;

create or replace function public.rotate_class_session_code(
    p_session_id bigint,
    p_teacher_id bigint,
    p_access_code text
)
returns setof public.class_sessions
language plpgsql
security invoker
set search_path = ''
as $$
declare
    v_session public.class_sessions%rowtype;
begin
    if p_access_code !~ '^[0-9]{8}$' then
        raise exception 'Invalid check-in code.';
    end if;

    update public.class_sessions
    set access_code = p_access_code
    where session_id = p_session_id
      and teacher_id = p_teacher_id
      and closed_at is null
      and expires_at > now()
    returning * into v_session;

    if not found then
        raise exception 'The check-in session is no longer active.';
    end if;

    return next v_session;
end;
$$;

create or replace function public.close_class_session(
    p_session_id bigint,
    p_teacher_id bigint
)
returns setof public.class_sessions
language plpgsql
security invoker
set search_path = ''
as $$
declare
    v_session public.class_sessions%rowtype;
begin
    select *
    into v_session
    from public.class_sessions
    where session_id = p_session_id
      and teacher_id = p_teacher_id
      and closed_at is null
    for update;

    if not found then
        raise exception 'The check-in session is already closed.';
    end if;

    update public.class_sessions
    set closed_at = now()
    where session_id = p_session_id
      and teacher_id = p_teacher_id
      and closed_at is null
    returning * into v_session;
    
    insert into public.attendance_logs (
        student_id, subject_id, timestamp, is_present, class_session_id
    )
    select enrollment.student_id,
           v_session.subject_id,
           now(),
           false,
           v_session.session_id
    from public.subject_students as enrollment
    where enrollment.subject_id = v_session.subject_id
      and not exists (
          select 1
          from public.class_checkins as checkin
          where checkin.session_id = v_session.session_id
            and checkin.student_id = enrollment.student_id
      )
    on conflict (class_session_id, student_id)
        where class_session_id is not null
        do nothing;

    return next v_session;
end;
$$;

create or replace function public.submit_class_checkin(
    p_access_code text,
    p_student_id bigint,
    p_subject_id bigint,
    p_verification_method text,
    p_verification_score double precision,
    p_latitude double precision,
    p_longitude double precision,
    p_location_accuracy_m double precision
)
returns setof public.class_checkins
language plpgsql
security invoker
set search_path = ''
as $$
declare
    v_session public.class_sessions%rowtype;
    v_checkin public.class_checkins%rowtype;
    v_status text;
    v_risk_flags text[] := '{}';
begin
    select *
    into v_session
    from public.class_sessions
    where access_code = p_access_code
      and closed_at is null
      and expires_at > now()
    for update;

    if not found then
        raise exception 'This class code is invalid, expired, or closed.';
    end if;

    if p_subject_id is not null and p_subject_id <> v_session.subject_id then
        raise exception 'This code belongs to a different class.';
    end if;

    if not exists (
        select 1
        from public.subject_students
        where subject_id = v_session.subject_id
          and student_id = p_student_id
    ) then
        raise exception 'You must be enrolled in this class to check in.';
    end if;

    if exists (
        select 1
        from public.class_checkins
        where session_id = v_session.session_id
          and student_id = p_student_id
    ) then
        raise exception 'A check-in has already been submitted for this session.';
    end if;

    if p_verification_method = 'face' then
        if p_verification_score < 0 or p_verification_score > 0.6 then
            raise exception 'Face verification did not match the saved profile.';
        elsif p_verification_score <= 0.45 then
            v_status := 'approved';
        else
            v_status := 'pending';
            v_risk_flags := array_append(v_risk_flags, 'borderline_face_match');
        end if;
    elsif p_verification_method = 'voice' then
        if p_verification_score < 0.65 or p_verification_score > 1 then
            raise exception 'Voice verification did not match the saved profile.';
        elsif p_verification_score >= 0.8 then
            v_status := 'approved';
        else
            v_status := 'pending';
            v_risk_flags := array_append(v_risk_flags, 'borderline_voice_match');
        end if;
    else
        raise exception 'Unsupported verification method.';
    end if;

    if p_latitude is not null and p_longitude is null
       or p_latitude is null and p_longitude is not null then
        raise exception 'Both GPS coordinates are required when sharing location.';
    end if;

    if p_location_accuracy_m > 200 then
        v_risk_flags := array_append(v_risk_flags, 'low_gps_accuracy');
    end if;

    insert into public.class_checkins (
        session_id, student_id, verification_method, verification_score,
        latitude, longitude, location_accuracy_m, risk_flags, status
    )
    values (
        v_session.session_id, p_student_id, p_verification_method,
        p_verification_score, p_latitude, p_longitude,
        p_location_accuracy_m, v_risk_flags, v_status
    )
    returning * into v_checkin;

    if v_status = 'approved' then
        insert into public.attendance_logs (
            student_id, subject_id, timestamp, is_present, class_session_id
        )
        values (
            p_student_id, v_session.subject_id, v_checkin.submitted_at, true,
            v_session.session_id
        )
        on conflict (class_session_id, student_id)
            where class_session_id is not null
            do update set
                timestamp = excluded.timestamp,
                is_present = true;
    else
        select * into v_session
        from public.class_sessions
        where session_id = v_checkin.session_id;

        insert into public.attendance_logs (
            student_id, subject_id, timestamp, is_present, class_session_id
        )
        values (
            v_checkin.student_id, v_session.subject_id,
            v_checkin.submitted_at, false, v_checkin.session_id
        )
        on conflict (class_session_id, student_id)
            where class_session_id is not null
            do nothing;
    end if;

    return next v_checkin;
end;
$$;

create or replace function public.review_class_checkin(
    p_checkin_id bigint,
    p_teacher_id bigint,
    p_approved boolean
)
returns setof public.class_checkins
language plpgsql
security invoker
set search_path = ''
as $$
declare
    v_checkin public.class_checkins%rowtype;
    v_session public.class_sessions%rowtype;
begin
    select checkin.*
    into v_checkin
    from public.class_checkins as checkin
    join public.class_sessions as session
      on session.session_id = checkin.session_id
    where checkin.checkin_id = p_checkin_id
      and checkin.status = 'pending'
      and session.teacher_id = p_teacher_id
    for update of checkin;

    if not found then
        raise exception 'This request was already reviewed or is not in your classes.';
    end if;

    update public.class_checkins
    set status = case when p_approved then 'approved' else 'rejected' end,
        reviewed_at = now(),
        reviewed_by = p_teacher_id
    where checkin_id = p_checkin_id
    returning * into v_checkin;

    if p_approved then
        select * into v_session
        from public.class_sessions
        where session_id = v_checkin.session_id;

        insert into public.attendance_logs (
            student_id, subject_id, timestamp, is_present, class_session_id
        )
        values (
            v_checkin.student_id, v_session.subject_id,
            v_checkin.submitted_at, true, v_checkin.session_id
        )
        on conflict (class_session_id, student_id)
            where class_session_id is not null
            do update set
                timestamp = excluded.timestamp,
                is_present = true;
    end if;

    return next v_checkin;
end;
$$;

create or replace function public.delete_student_account(p_student_id bigint)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
begin
    delete from public.attendance_logs where student_id = p_student_id;
    if to_regclass('public.voice_attendance_submissions') is not null then
        execute
            'delete from public.voice_attendance_submissions where student_id = $1'
        using p_student_id;
    end if;
    delete from public.class_checkins where student_id = p_student_id;
    delete from public.subject_students where student_id = p_student_id;
    delete from public.students where student_id = p_student_id;
    return found;
end;
$$;

